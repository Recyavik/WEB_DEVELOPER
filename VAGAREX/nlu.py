def extract_arc_angle(text: str, default: float = 90.0) -> float:
    """Извлечь угол дуги в градусах из голосовой/текстовой команды «дуга N».
    Поддерживает «дуга 90», «дуга 90 градусов», «дуга по часовой 180»,
    «дуга 360». Без числа — возвращает `default` (90°)."""
    n = norm(text)
    # «N градусов» — самый частый случай.
    m = re.search(r'(\d+\.?\d*)\s*(?:градус|°)', n)
    if m:
        return max(1.0, min(3600.0, float(m.group(1))))
    # Просто число после «дуг…»: «дуга 90», «дуга по часовой 180».
    m = re.search(r'\bдуг[аиуоые]\w*(?:\s+\S+)*?\s+(\d+\.?\d*)', n)
    if m:
        return max(1.0, min(3600.0, float(m.group(1))))
    # Просто первое число в фразе (на случай если «дуга» в середине).
    m = re.search(r'(\d+\.?\d*)', n)
    if m:
        return max(1.0, min(3600.0, float(m.group(1))))
    return float(default)


