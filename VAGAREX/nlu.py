def predict(text: str) -> Tuple[Optional[str], float]:
    n = norm(text)
    for intent, phrases in _RULES:
        for ph in phrases:
            if callable(ph):
                if ph(n):
                    return intent, 1.0
            elif ph in n:
                return intent, 1.0
    return None, 0.0


# ── Извлечение параметров ────────────────────────────────────────────────────

def extract_speed(text: str, default: int = 40) -> int:
    n = norm(text)
    m = re.search(r'скорость\s+(\d+)', n)
    if m:
        return max(5, min(100, int(m.group(1))))
    m = re.search(r'(\d+)\s*(?:процент|%)', n)
    if m:
        return max(5, min(100, int(m.group(1))))
    if any(w in n for w in ("быстро", "быстрый", "максимум", "полная скорость")):
        return 80
    if any(w in n for w in ("медленно", "медленный", "тихо", "потихоньку")):
        return 20
    if any(w in n for w in ("спокойно", "спокойный", "средне")):
        return 40
    return default


def extract_distance(text: str) -> Optional[int]:
    """Возвращает дистанцию в сантиметрах или None (непрерывное движение)."""
    n = norm(text)
    m = re.search(r'(\d+)\s*(?:метр|м\b)', n)
    if m:
        return max(5, min(2000, int(m.group(1)) * 100))
    m = re.search(r'(\d+)\s*(?:сантиметр|см)', n)
    if m:
        return max(5, min(2000, int(m.group(1))))
    m = re.search(r'(?:вперед|назад)\s+(\d+)(?!\s*(?:градус|°))', n)
    if m:
        val = int(m.group(1))
        # Раньше был порог `val > 10` как защита от ложных срабатываний
        # на короткие числа, но он ломал короткие команды вроде «вперёд 5»:
        # без единицы измерения число игнорировалось, forward уходил в
        # непрерывный режим. Любое положительное число — это дистанция.
        if val > 0:
            return max(5, min(2000, val))
    return None


def extract_angle(text: str) -> Optional[int]:
    """Угол руля 1–45°. None если не указан.

    Любое положительное число клампится в [1; 45] — плата 1T REX
    физически не повернёт руль дальше ±45°, поэтому большее значение
    из голоса/текста обрезаем без потери смысла команды."""
    n = norm(text)
    m = re.search(r'(\d+)\s*(?:градус|°)', n)
    if m:
        return max(1, min(45, int(m.group(1))))
    m = re.search(r'(?:направо|налево|вправо|влево)\s+(\d+)', n)
    if m:
        val = int(m.group(1))
        if val > 0:
            return max(1, min(45, val))
    return None


def extract_course(text: str) -> Optional[int]:
    """Извлекает целевой курс: «курс 90» → 90."""
    n = norm(text)
    m = re.search(r'курс\s+(\d+)', n)
    if m:
        return int(m.group(1)) % 360
    return None


def extract_face_angle(text: str) -> Optional[int]:
    """Извлекает угол для поворота на месте. Все эти фразы эквивалентны и
    дают один и тот же вызов face_cmd(N):
      «поверни на 70»          «лицом на 70»
      «повернись на 70»        «развернись на 90 градусов»
      «поворот на 70»          «разверни на -45»
      «повернуть на 70»        «повернуться на 70»
      «развернуть на 70»       «развернуться на 70»
    Возвращает int 0..359 (отрицательные нормализуются по модулю 360)."""
    n = norm(text)
    m = re.search(
        r'(?:поверни|повернись|повернуть|повернуться|поворот|'
        r'разверни|развернись|развернуть|развернуться|лицом)'
        r'\s+на\s+(-?\d+)',
        n)
    if m:
        return int(m.group(1)) % 360
    return None


def extract_color(text: str) -> Optional[tuple]:
    """Возвращает RGB-цвет по словесному названию."""
    n = norm(text)
    colors = {
        "красн": (255, 0, 0),
        "зелен": (0, 255, 0),
        "син": (0, 0, 255),
        "бел": (255, 255, 255),
        "желт": (255, 255, 0),
        "фиолет": (128, 0, 128),
        "голуб": (0, 255, 255),
    }
    for key, value in colors.items():
        if key in n:
            return value
    return None


def extract_default_turn_angle(text: str, default: int = 35) -> int:
    """«угол руля 30», «руль по умолчанию 25» → 30/25. Клампим 1..45."""
    n = norm(text)
    for pat in (
        r'(?:угол\s+руля|руль\s+по\s+умолчанию|поворот\s+по\s+умолчанию)\s+(\d+)',
        r'(\d+)\s*(?:градус|°)',
    ):
        m = re.search(pat, n)
        if m:
            return max(1, min(45, int(m.group(1))))
    return default


def extract_kturn_steps(text: str) -> int:
    """Извлекает число приемов разворота. По умолчанию 3."""
    n = norm(text)
    for pat in (
        r'за\s+(\d+)\s*(?:раза?|шаг|шага|шагов|прием|приема|приемов)',
        r'в\s+(\d+)\s*(?:раза?|шаг|шага|шагов|прием|приема|приемов)',
        r'(\d+)\s*(?:раза?|шаг|шага|шагов|прием|приема|приемов)',
    ):
        m = re.search(pat, n)
        if m:
            return max(1, min(10, int(m.group(1))))
    return 3


def extract_coordinates(text: str) -> Optional[Tuple[float, float]]:
    """Извлекает (X, Y) из произвольной записи.

    Поддержанные варианты:
      «в точку -50 -50», «в точку -50,-50», «в точку (-50, -50)»,
      «в точку - 50 -50» (пробел между минусом и числом),
      «в точку минус 50 минус 50» (ASR произносит «минус» словом).

    Регрессия (bug v4.x): regex `(-?\\d+)\\s+(-?\\d+)` ломался на
    «- 50 -50» — минус отделялся пробелом от числа и группа 1 захватывала
    «50» без знака. Теперь предварительно склеиваем «- 50» → «-50»
    и убираем запятые/скобки."""
    n = norm(text)
    # «минус 50» → «-50» (ASR-произношение слова «минус» вместо знака)
    n = re.sub(r'\bминус\s+(\d)', r'-\1', n)
    # Запятые и скобки → пробел (упрощаем разделители)
    n = re.sub(r'[(),]', ' ', n)
    # «- 50» → «-50» (склеиваем минус с числом)
    n = re.sub(r'-\s+(\d)', r'-\1', n)
    # Нормализуем подряд идущие пробелы
    n = re.sub(r'\s+', ' ', n).strip()
    m = re.search(r'(-?\d+\.?\d*)\s+(-?\d+\.?\d*)', n)
    if m:
        return float(m.group(1)), float(m.group(2))
    return None


def extract_pause_seconds(text: str) -> float:
    """Длительность паузы в секундах. По умолчанию 1 сек."""
    n = norm(text)
    m = re.search(r'пауза\s+(\d+\.?\d*)', n)
    if m:
        return max(0.1, min(60.0, float(m.group(1))))
    m = re.search(r'(\d+\.?\d*)\s*(?:сек|секунд|с\b)', n)
    if m:
        return max(0.1, min(60.0, float(m.group(1))))
    m = re.search(r'(?:подожди|ждать|задержка|ожидание|стой|стоять)\s+(\d+\.?\d*)', n)
    if m:
        return max(0.1, min(60.0, float(m.group(1))))
    return 1.0


def extract_radius(text: str) -> Optional[float]:
    """Радиус зоны (см).
    Поддерживает форматы:
      • «радиус 30», «r=30», «r 30»
      • третье позиционное число после координат: «100 -50 30»
        (X, Y, RADIUS — в одной фразе);
      • одиночное число в фразе без координат: «зона внимание 30»,
        «опасная зона 30» — единственное число трактуется как радиус."""
    n = norm(text)
    # 1) Явное указание «радиус 30» / «r=30»
    m = re.search(r'(?:радиус|\br\b)\s*=?\s*(\d+\.?\d*)', n)
    if m:
        return max(5.0, min(500.0, float(m.group(1))))
    # 2) Третье число подряд после двух координат: «X Y R»
    m = re.search(r'(-?\d+\.?\d*)\s+(-?\d+\.?\d*)\s+(\d+\.?\d*)', n)
    if m:
        return max(5.0, min(500.0, float(m.group(3))))
    # 3) Одиночное число без координат: «зона внимание 30» → 30.
    nums = re.findall(r'-?\d+\.?\d*', n)
    if len(nums) == 1:
        return max(5.0, min(500.0, float(nums[0])))
    return None


