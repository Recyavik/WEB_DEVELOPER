_ASR_FIXES = {
    "бэга": "вега", "вэга": "вега", "вига": "вега", "бега": "вега",
    "сотп": "стоп",
    "налева": "налево", "направа": "направо",
    "вперод": "вперед", "вперед": "вперед",
    "взад": "назад",
}

def norm(text: str) -> str:
    t = text.lower().strip()
    t = re.sub(r'[её]', 'е', t)
    t = re.sub(r'\s+', ' ', t)
    for wrong, right in _ASR_FIXES.items():
        t = t.replace(wrong, right)
    return t


# ── Активатор ────────────────────────────────────────────────────────────────

WAKE_VARIANTS = {"вега", "вэга", "вига", "бега"}

def has_wake(text: str) -> bool:
    words = norm(text).split()
    return bool(set(words[:4]) & WAKE_VARIANTS)


